// Generate the 64×64 blue-noise threshold mask with the void-and-cluster method
// (R. Ulichney, "Void-and-cluster method for dither array generation", Proc. SPIE 1913, 1993).
// Writes src/dither/blue-noise-64.ts. Deterministic: same seed, same mask.
// Usage: node scripts/gen-blue-noise.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const N = 64
const SIGMA = 1.5
const SEED = 1
const AREA = N * N

function mulberry32(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// Toroidal Gaussian kernel: weight between any two cells depends only on their wrapped offset.
const kernel = new Float64Array(AREA)
for (let y = 0; y < N; y++) {
  for (let x = 0; x < N; x++) {
    const dx = Math.min(x, N - x)
    const dy = Math.min(y, N - y)
    kernel[y * N + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))
  }
}

/** Add `sign` × kernel centred on cell `i` to the energy field. */
function splat(energy, i, sign) {
  const cx = i % N
  const cy = (i / N) | 0
  for (let y = 0; y < N; y++) {
    const ky = ((y - cy + N) % N) * N
    const row = y * N
    for (let x = 0; x < N; x++) energy[row + x] += sign * kernel[ky + ((x - cx + N) % N)]
  }
}

function energyOf(pattern, value) {
  const e = new Float64Array(AREA)
  for (let i = 0; i < AREA; i++) if (pattern[i] === value) splat(e, i, 1)
  return e
}

/** Index of the highest (or lowest) energy among cells whose pattern equals `value`. */
function extreme(energy, pattern, value, highest) {
  let best = -1
  let bestE = highest ? -Infinity : Infinity
  for (let i = 0; i < AREA; i++) {
    if (pattern[i] !== value) continue
    const e = energy[i]
    if (highest ? e > bestE : e < bestE) {
      bestE = e
      best = i
    }
  }
  return best
}

// 1. Initial binary pattern: about 10% minority pixels, then relaxed by moving the
//    tightest cluster into the largest void until the two coincide.
const rand = mulberry32(SEED)
const initial = new Uint8Array(AREA)
const ones = Math.round(AREA * 0.1)
let placed = 0
while (placed < ones) {
  const i = Math.floor(rand() * AREA)
  if (!initial[i]) {
    initial[i] = 1
    placed++
  }
}
{
  const e = energyOf(initial, 1)
  for (;;) {
    const cluster = extreme(e, initial, 1, true)
    initial[cluster] = 0
    splat(e, cluster, -1)
    const voidAt = extreme(e, initial, 0, false)
    if (voidAt === cluster) {
      initial[cluster] = 1
      splat(e, cluster, 1)
      break
    }
    initial[voidAt] = 1
    splat(e, voidAt, 1)
  }
}

const rank = new Int32Array(AREA).fill(-1)

// 2. Phase one: remove the tightest cluster repeatedly; ranks count down from ones - 1.
{
  const p = Uint8Array.from(initial)
  const e = energyOf(p, 1)
  for (let r = ones - 1; r >= 0; r--) {
    const c = extreme(e, p, 1, true)
    p[c] = 0
    splat(e, c, -1)
    rank[c] = r
  }
}

// 3. Phase two: fill the largest void up to half the cells.
const p = Uint8Array.from(initial)
{
  const e = energyOf(p, 1)
  for (let r = ones; r < AREA / 2; r++) {
    const v = extreme(e, p, 0, false)
    p[v] = 1
    splat(e, v, 1)
    rank[v] = r
  }
}

// 4. Phase three: the zeros are now the minority; fill the tightest cluster of zeros.
{
  const e = energyOf(p, 0)
  for (let r = AREA / 2; r < AREA; r++) {
    const c = extreme(e, p, 0, true)
    p[c] = 1
    splat(e, c, -1)
    rank[c] = r
  }
}

// Sanity: ranks are a permutation of 0..AREA-1.
const seen = new Uint8Array(AREA)
for (const r of rank) {
  if (r < 0 || r >= AREA || seen[r]) throw new Error('ranks are not a permutation')
  seen[r] = 1
}

const bytes = Buffer.alloc(AREA * 2)
for (let i = 0; i < AREA; i++) bytes.writeUInt16LE(rank[i], i * 2)
const b64 = bytes.toString('base64')
const lines = b64.match(/.{1,100}/g).map((l) => `  '${l}',`)

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'dither', 'blue-noise-64.ts')
writeFileSync(
  out,
  `// Generated by scripts/gen-blue-noise.mjs (void-and-cluster, ${N}×${N}, sigma ${SIGMA}, seed ${SEED}). Do not edit.
// Each cell holds its rank 0..${AREA - 1} as a little-endian uint16, base64-encoded.

/** Side length of the blue-noise mask. */
export const BLUE_NOISE_SIZE = ${N}

/** The mask's ranks, base64 of ${AREA} little-endian uint16 values. */
export const BLUE_NOISE_64_B64 = [
${lines.join('\n')}
].join('')
`,
)
console.log(`wrote ${out}`)
